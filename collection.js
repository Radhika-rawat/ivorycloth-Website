const collectionType =
    document.body.dataset.collection || "dresses";

let currentProducts;

if (collectionType === "clothing") {

    currentProducts = [
        ...products.dresses,
        ...products.tops,
        ...products.bottoms,
        ...products.accessories
    ];

} else {

    currentProducts =
        products[collectionType] || products.dresses;

}





const productContainer =
    document.getElementById("collectionProducts");

const sortSelect =
    document.getElementById("sortProducts");

const loadMoreButton =
    document.getElementById("loadMore");





let productsToShow = 12;

let activeProducts =
    [...currentProducts];





function displayProducts() {

    if (!productContainer) {
        return;
    }

    productContainer.innerHTML = "";


    const visibleProducts =
        activeProducts.slice(0, productsToShow);


    if (visibleProducts.length === 0) {

        productContainer.innerHTML = `
            <div class="no-products">
                <h2>No products found</h2>
                <p>
                    Try changing your filters.
                </p>
            </div>
        `;

        if (loadMoreButton) {
            loadMoreButton.style.display = "none";
        }

        return;
    }


    visibleProducts.forEach(product => {

        const card =
            document.createElement("article");

        card.className = "product-card";


        card.innerHTML = `

            <div class="collection-product-image">

                <img
                    src="${product.image}"
                    alt="${product.name}"
                    onerror="this.src='https://via.placeholder.com/600x750?text=Image+Not+Found'"
                >

                <button
                    class="product-heart"
                    data-id="${product.id}"
                    aria-label="Add to wishlist"
                >
                    ♡
                </button>

            </div>


            <div class="collection-product-info">

                <p class="product-category">
                    ${product.category}
                </p>

                <h3>
                    ${product.name}
                </h3>

                <div class="product-rating">
                    ★★★★★
                    <span>
                        ${product.rating}
                    </span>
                </div>

                <div class="product-price">
                    ₹${product.price.toLocaleString("en-IN")}
                </div>

                <button
                    class="add-cart"
                    data-id="${product.id}"
                >
                    ADD TO BAG
                </button>

            </div>

        `;


        productContainer.appendChild(card);

    });


    setupProductButtons();


    if (loadMoreButton) {

        if (productsToShow >= activeProducts.length) {

            loadMoreButton.style.display =
                "none";

        } else {

            loadMoreButton.style.display =
                "block";

        }

    }

}





function setupProductButtons() {

    /* ==============
       WISHLIST
    ================ */

    document
        .querySelectorAll(".product-heart")
        .forEach(button => {

            button.addEventListener(
                "click",
                function () {

                    this.classList.toggle("liked");

                    if (this.classList.contains("liked")) {

                        this.innerHTML = "♥";

                    } else {

                        this.innerHTML = "♡";

                    }

                }
            );

        });



    /* =========================
       ADD TO CART
    ========================= */

    document
        .querySelectorAll(".add-cart")
        .forEach(button => {

            button.addEventListener(
                "click",
                function () {

                    const id =
                        Number(this.dataset.id);

                    const product =
                        currentProducts.find(
                            item => item.id === id
                        );

                    if (!product) {
                        return;
                    }


                    addToCart(product);


                    this.innerHTML =
                        "✓ ADDED";


                    setTimeout(() => {

                        this.innerHTML =
                            "ADD TO BAG";

                    }, 1200);

                }
            );

        });

}



/* =========
   7. CART
========= */

function addToCart(product) {

    let cart =
        JSON.parse(
            localStorage.getItem("ivoryCart")
        ) || [];


    const existing =
        cart.find(
            item => item.id === product.id
        );


    if (existing) {

        existing.quantity++;

    } else {

        cart.push({

            ...product,

            quantity: 1

        });

    }


    localStorage.setItem(
        "ivoryCart",
        JSON.stringify(cart)
    );


    updateCartCount();

}



/* ==========
   8. CART COUNT
============ */

function updateCartCount() {

    const cart =
        JSON.parse(
            localStorage.getItem("ivoryCart")
        ) || [];


    const count =
        cart.reduce(
            (total, item) =>
                total + item.quantity,
            0
        );


    document
        .querySelectorAll(".cart-count")
        .forEach(element => {

            element.textContent = count;

        });

}





if (sortSelect) {

    sortSelect.addEventListener(
        "change",
        function () {

            const value =
                this.value;


            if (value === "low") {

                activeProducts.sort(
                    (a, b) =>
                        a.price - b.price
                );

            }


            else if (value === "high") {

                activeProducts.sort(
                    (a, b) =>
                        b.price - a.price
                );

            }


            else if (value === "rating") {

                activeProducts.sort(
                    (a, b) =>
                        b.rating - a.rating
                );

            }


            else {

                activeProducts =
                    [...currentProducts];

            }


            productsToShow = 12;

            displayProducts();

        }
    );

}



/* =========================================================
   10. LOAD MORE
========================================================= */

if (loadMoreButton) {

    loadMoreButton.addEventListener(
        "click",
        function () {

            productsToShow += 6;

            displayProducts();

        }
    );

}





document
    .querySelectorAll(".collection-options button")
    .forEach(button => {

        button.addEventListener(
            "click",
            function () {

                document
                    .querySelectorAll(
                        ".collection-options button"
                    )
                    .forEach(btn => {

                        btn.classList.remove(
                            "active"
                        );

                    });


                this.classList.add("active");


                const category =
                    this.textContent
                        .trim()
                        .toLowerCase();


                if (
                    category.startsWith("all")
                ) {

                    activeProducts =
                        [...currentProducts];

                } else {

                    activeProducts =
                        currentProducts.filter(
                            product =>
                                product.type
                                    .toLowerCase()
                                    .includes(category)
                        );

                }


                productsToShow = 12;

                displayProducts();

            }
        );

    });



/* ===
   12. FILTERS
==== */

document
    .querySelectorAll(
        ".filters input[type='checkbox']"
    )
    .forEach(checkbox => {

        checkbox.addEventListener(
            "change",
            applyFilters
        );

    });



function applyFilters() {

    const checked =
        Array.from(
            document.querySelectorAll(
                ".filters input[type='checkbox']:checked"
            )
        );


    if (checked.length === 0) {

        activeProducts =
            [...currentProducts];

        productsToShow = 12;

        displayProducts();

        return;

    }


    activeProducts =
        currentProducts.filter(product => {

            return checked.some(filter => {

                const value =
                    filter.value.toLowerCase();


                return (
                    product.type
                        .toLowerCase()
                        .includes(value)
                    ||
                    product.color
                        .toLowerCase()
                        .includes(value)
                );

            });

        });


    productsToShow = 12;

    displayProducts();

}



/* ===
   13. SEARCH
===== */

const searchIcon =
    document.querySelector(".search-icon");


if (searchIcon) {

    searchIcon.addEventListener(
        "click",
        function () {

            const search =
                prompt(
                    "What are you looking for?"
                );


            if (!search) {
                return;
            }


            const query =
                search
                    .toLowerCase()
                    .trim();


            activeProducts =
                currentProducts.filter(
                    product =>
                        product.name
                            .toLowerCase()
                            .includes(query)
                        ||
                        product.category
                            .toLowerCase()
                            .includes(query)
                        ||
                        product.type
                            .toLowerCase()
                            .includes(query)
                );


            productsToShow = 12;

            displayProducts();

        }
    );

}




   

displayProducts();

updateCartCount();

